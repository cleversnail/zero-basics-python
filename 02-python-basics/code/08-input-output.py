# 08-input-output.py
# 第 8 讲 · 修炼基本功：浅析输入输出
#
# 计算机的三个基本动作：输入 → 计算/存储 → 输出。
# 本讲用两个内置函数完成输入和输出：
#   input()  —— 从键盘读入一行内容（会停下来等你敲键盘）
#   print()  —— 把内容显示到屏幕上

# 1) 最简单的输出
print("Hello Python!")

# 2) 输入：讲义里是这样写的（会等你输入，文档里无法演示）
#    var1 = input("输入第一行内容\n")
#    var2 = input("输入第二行内容\n")
#    下面用固定值代替键盘输入，效果完全等价：
var1 = "这是第一行"
var2 = "这是第二行"

# 3) 任务：把输入的两行“以相反的顺序”输出
print("第二行的内容是")
print(var2)
print("第一行的内容是")
print(var1)

# 4) 课后作业：把用户输入的一行内容连续输出三次
#    讲义写法是 var = input(); print(var) 三次，这里同样用固定值代替
line = "我学会了输入输出"
print(line)
print(line)
print(line)
