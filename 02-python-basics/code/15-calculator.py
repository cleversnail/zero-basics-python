# 15-calculator.py
# 第 15 讲 · 小试牛刀：如何制作简单计算器？
#
# 需求：用户输入两个数和运算符，程序算出结果。
# 关键点：input() 读进来的其实是字符串，而字符串没法做算术运算，
#        所以要么先转成数字，要么交给 eval() 去执行这个“表达式字符串”。

# ---------- 版本一：只算加法 ----------
# 讲义写法：
#   num1 = input("输入一个数字")
#   num2 = input("输入一个数字")
#   sum = eval(f"{num1}+{num2}")
#   print(sum)
# 交互输入无法在文档里演示，这里用固定值代替键盘输入。
num1 = "12"
num2 = "30"
total = eval(f"{num1}+{num2}")
print(total)

# ---------- 版本二：支持四则运算的计算器 ----------
# 用户输入两个数和一个运算符，把它拼成表达式字符串交给 eval()
a = "8"
b = "4"
op = "*"
result = eval(f"{a}{op}{b}")
print(f"计算结果为{result}")

# 课后作业：支持浮点数的四则运算计算器
# 直接把小数点也拼进表达式里，eval 会自动按浮点数处理
a = "1.5"
b = "2.5"
op = "+"
result = eval(f"{a}{op}{b}")
print(f"计算结果为{result}")
