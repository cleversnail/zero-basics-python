# 13-number-vs-string.py
# 第 13 讲 · 何时使用数字，何时使用字符串？
#
# 字符串管“文字 / 统计 / 语义”，数字管“计算”。
# Python 是强类型语言：类型不会在运算中途悄悄改变，必须显式转换。

# 1) 数字：做算术
print(100 + 200)

# 2) 数字比较：按大小比
print(456 > 1234)

# 3) 字符串：做拼接（不是加法！）
print("100" + "200")

# 4) 字符串比较：按“字典序”（逐位比字符的编码），不是比大小
print("456" > "1234")

# 5) 想比长度，得先取长度
print(len("456") > len("1234"))

# 6) 不同类型不能直接运算，否则报 TypeError
#    这里用 try/except 把错误抓住打印出来，方便观察
try:
    print(123 + "456")
except TypeError as err:
    print("TypeError:", err)
